#!/bin/bash
# android-stubs.sh: stand-ins for the libraries libbo1.so needs that cannot load outside a real Android process
# (libandroid.so and the GL libraries pull the whole framework; SDL needs its Java side). Every function the engine
# library imports from them exists and returns 0, which is all a dedicated server asks. For run-android.sh only.
NDK=/bo1/ndk/ndk-r30/android-ndk-r30/toolchains/llvm/prebuilt/linux-x86_64
OUT=/bo1/android/stubs; mkdir -p $OUT; cd $OUT || exit 1
LIB=/bo1/p32tree/build/android/bin/libbo1.so
llvm-nm-21 -D --undefined-only $LIB | awk '{print $2}' | sed 's/@.*//' | sort -u > undefined.txt
make_stub() {  # <library name> <symbol regex>
  grep -E "$2" undefined.txt > $1.syms
  { echo "/* generated by android-stubs.sh */"; while read s; do echo "long $s(void) { return 0; }"; done < $1.syms; } > $1.c
  $NDK/bin/clang --target=aarch64-linux-android26 -shared -fPIC -Wno-incompatible-library-redeclaration -o lib$1.so $1.c -Wl,-soname,lib$1.so || exit 1
  echo "lib$1.so: $(wc -l < $1.syms) functions"
}
make_stub SDL2 '^SDL_'
make_stub GLESv3 '^gl[A-Z]'
make_stub EGL '^egl[A-Z]'
make_stub android '^A[A-Z][A-Za-z]*_'
